class InventoryCountRecord(ArangoDocument): # edge collection inventory_count_record
  # What was counted
  product_id: str = Field(..., alias='_from', description="ArangoDB document ID of the product being counted (`Product/<key>`).", examples=["Product/67890"])
  position_id: str = Field(..., alias='_to', description="ArangoDB document ID of the position being counted (`Position/<key>`).", examples=["Position/12345"])

  # Core data - see validation below for ensuring correct setting
  system_qt: float = Field(..., description="System quantity snapshot taken at count start. Re-taken if the count record is updated before submission.", examples=[50.0])
  system_serial_keys: list[str] | None = Field(None, description="System serial keys snapshot at count start.", examples=[["SN-LR-001234"]])
  system_at: datetime | None = Field(default_factory=timestamp, description="Timestamp of the system quantity snapshot.", examples=["2026-05-20T08:00:00Z"])

  counted_qt: float | None = Field(None, description="Physical quantity found during count. Always set for non-started records.", examples=[48.0])
  counted_serial_keys: list[str] | None = Field(None, description="Serial keys physically found during count. If provided, must match `counted_qt`.", examples=[["SN-LR-001234"]])
  counted_at: datetime | None = Field(None, description="Timestamp when the physical count was recorded.", examples=["2026-05-20T09:15:00Z"])

  # Metadata
  inventory_count_session_key: str = Field(..., description="Key of the parent counting session.", examples=["cnt-session-001"])
  assignment_key: str | None = Field(None, description="Key of the assignment this record belongs to.", examples=["assign-001"])
  user_key: str | None = Field(None, description="User key of the operator who started the count.", examples=["user/operator-01"])
  status: InventoryCountStatus = Field(InventoryCountStatus.STARTED, description="Current status of the count record.", examples=["completed"])
  reviewed_at: datetime | None = Field(None, description="Timestamp when the record was confirmed or discarded during review.", examples=["2026-05-20T10:00:00Z"])
  processed: bool | None = Field(False, description="True when this record has been evaluated by `CountSessionAppliedEvent`.", examples=[False])
  movement_keys: list[str] | None = Field(None, description="Keys of adjustment movements generated when this record was applied.", examples=[["mvt-adj-001"]])
  notes: str | None = Field(None, description="Free-text notes from the counting operator.", examples=["Found 2 extra units on top shelf"])
  extra: Any = Field(None, description="Arbitrary extra metadata.", examples=[None])

  @property
  def product_key(self) -> str:
    return self.product_id.split('/')[-1]

  @property
  def position_key(self) -> str:
    return self.position_id.split('/')[-1]

  @property
  def delta(self) -> float | None:
    return self.counted_qt - self.system_qt

  @model_validator(mode='after')
  def handle_serials(self):
    # Ensure actual counts are recorded correctly
    if self.status != InventoryCountStatus.STARTED:
      if self.counted_serial_keys is not None and len(self.counted_serial_keys) > 0:
        serial_count = len(self.counted_serial_keys)
        if self.counted_qt is None:
          self.counted_qt = serial_count
        elif self.counted_qt != serial_count:
          raise ValueError(
            "serial qt must be equal to the number of serial_keys if provided: "
            f"Serial qt: {self.counted_qt}, serial_count: {serial_count}"
          )
      elif self.counted_qt is None:
        raise ValueError("You must provide either a counted quantity or a list of serial keys found")
    return self


