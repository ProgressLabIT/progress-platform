class InventorySnapshotSource(str, Enum):
  IMPORT = 'import'
  MRP = 'mrp'
  COUNT_SESSION = 'count_session'

class InventorySnapshotType(str, Enum):
  VIRTUAL = 'virtual'
  ACTUAL = 'actual'

class InventorySnapshotScopeType(str, Enum):
  FULL = 'full'
  POSITIONS = 'positions'
  PRODUCTS = 'products'

class InventorySnapshot(ArangoDocument):
  snapshot_type: InventorySnapshotType = Field(..., description="Whether this is a `virtual` (planned/projected) or `actual` (physical count) snapshot.", examples=["actual"])
  source: InventorySnapshotSource = Field(..., description="Source that generated this snapshot.", examples=["count_session"])
  inventory_count_session_key: str | None = Field(None, description="Key of the counting session that produced this snapshot (required when `source=count_session`).", examples=["cnt-session-001"])
  timestamp: datetime = Field(default_factory=timestamp, description="Timestamp when the snapshot was taken.", examples=["2026-05-20T08:00:00Z"])

  # Scope
  scope_type: InventorySnapshotScopeType = Field(InventorySnapshotScopeType.FULL, description="Coverage scope: `full` captures all inventory; `positions` or `products` scopes to a subset.", examples=["full"])
  target_keys: list[str] | None = Field(None, description="Keys of the positions or products in scope (used when `scope_type` is not `full`).", examples=[["12345", "67890"]])

  created_by: str | None = Field(None, description="User key of the operator who initiated the snapshot.", examples=["user/manager-01"])
  notes: str | None = Field(None, description="Free-text notes for the snapshot.", examples=["Pre-count baseline Q2 2026"])
  extra: Any = Field(None, description="Arbitrary extra metadata.", examples=[None])

  @model_validator(mode='after')
  def validate_session_relationship(self):
    # Session snapshots MUST have a session reference
    if self.source == InventorySnapshotSource.COUNT_SESSION and not self.inventory_count_session_key:
      raise ValueError("Count session snapshots must have a session reference")

    return self

